#!/usr/bin/env python3
"""Which asop-spec release introduced each field — and what a newer release adds.

Two jobs, one introspection:

    python tools/asop_fields.py regenerate [VERSION ...]
        Install each released asop-spec into a throwaway directory, read its
        field lists, and rewrite agentco/field_provenance.py (field -> the first
        release that has it). Default versions: every one already in the table
        plus any given. Run it when the lock moves; a test fails until you do.

    python tools/asop_fields.py watch [--github]
        Ask PyPI for the newest asop-spec. If it is newer than the lock, list
        the fields it has that this hub neither knows (the provenance table)
        nor stores (the ASOP record's columns), and print the proposed update.
        With --github, open ONE issue titled
        "asop-spec X.Y.Z adds fields the hub does not forward: <list>"
        unless an open issue with that title exists, and write the job summary.

The hub itself never calls this and never touches the network: the runtime reads
only the generated table (agentco/field_provenance.py).

Introspection runs each version in its own subprocess with `python -I` and a
`--target` install, so no version is ever imported into this process and two
versions never share a sys.path.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path
from typing import Iterable, Mapping, Optional

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "agentco" / "field_provenance.py"
LOCK = ROOT / "uv.lock"
PYPI = "https://pypi.org/pypi/asop-spec/json"

# The surfaces a field can belong to, and how to read each from the installed
# contract. Run inside the target version's interpreter; absent ones are empty.
DUMP = r"""
import dataclasses, json
from asop.sop import ASOP, Step
import asop.gates as g
try:
    from asop.chain import CHAIN_FIELDS
except ImportError:
    CHAIN_FIELDS = ()
print(json.dumps({
    "asop": [f.name for f in dataclasses.fields(ASOP)],
    "step": [f.name for f in dataclasses.fields(Step)],
    "gate": list(g.GATE_FIELDS),
    "attestation": list(getattr(g, "ATTESTATION_FIELDS", ())),
    "chain": list(CHAIN_FIELDS),
}))
"""


def version_key(version: str) -> tuple:
    return tuple(int(p) if p.isdigit() else p for p in re.split(r"[.\-]", version))


def introspect(version: str) -> dict[str, list[str]]:
    """The field lists of one released version, read in isolation."""
    with tempfile.TemporaryDirectory() as target:
        # pip when this interpreter has it; uv otherwise (a uv-built venv has no pip).
        has_pip = subprocess.run([sys.executable, "-m", "pip", "--version"], capture_output=True).returncode == 0
        install = ([sys.executable, "-m", "pip", "install", "--quiet"] if has_pip or not shutil.which("uv")
                   else ["uv", "pip", "install", "--quiet", "--python", sys.executable])
        subprocess.run([*install, "--no-deps", "--target", target, f"asop-spec=={version}"], check=True)
        out = subprocess.run([sys.executable, "-I", "-c", f"import sys; sys.path.insert(0, {target!r})\n{DUMP}"],
                             check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def provenance(dumps: Mapping[str, Mapping[str, Iterable[str]]]) -> dict[str, dict[str, str]]:
    """{surface: {field: first version that has it}}, versions in release order."""
    out: dict[str, dict[str, str]] = {}
    for version in sorted(dumps, key=version_key):
        for surface, names in dumps[version].items():
            for name in names:
                out.setdefault(surface, {}).setdefault(name, version)
    return {s: dict(sorted(f.items())) for s, f in sorted(out.items())}


def render(table: Mapping[str, Mapping[str, str]], releases: Iterable[str]) -> str:
    releases = sorted(releases, key=version_key)
    return (
        '"""Field provenance: the first asop-spec release that has each field.\n\n'
        "GENERATED by tools/asop_fields.py regenerate — do not edit by hand. The hub reads\n"
        "this to say, when a request names a field it does not take, whether a newer\n"
        "release has it (agentco/wire.py). It never calls the network.\n"
        '"""\n\n'
        f"RELEASES: tuple[str, ...] = {tuple(releases)!r}\n\n"
        f"FIELDS: dict[str, dict[str, str]] = {json.dumps(table, indent=4, sort_keys=True)}\n"
    )


def known_releases() -> list[str]:
    if not TABLE.exists():
        return []
    namespace: dict = {}
    exec(TABLE.read_text(), namespace)  # noqa: S102 - our own generated file
    return list(namespace.get("RELEASES", ()))


def locked_version(lock_text: str) -> Optional[str]:
    match = re.search(r'\[\[package\]\]\nname = "asop-spec"\nversion = "([^"]+)"', lock_text)
    return match.group(1) if match else None


def latest_on_pypi(url: str = PYPI) -> str:
    with urllib.request.urlopen(url, timeout=30) as response:  # noqa: S310 - fixed https URL
        return json.load(response)["info"]["version"]


def new_fields(newest: Mapping[str, Iterable[str]], table: Mapping[str, Mapping[str, str]],
               record_columns: Iterable[str]) -> dict[str, list[str]]:
    """What the newest release has that the hub neither knows nor stores.

    A field is "new" if the provenance table has no entry for it on its surface.
    ASOP record fields are also checked against the record's storage columns: a
    known field the hub has no column for is just as unforwarded."""
    columns = set(record_columns)
    out: dict[str, list[str]] = {}
    for surface, names in newest.items():
        known = set(table.get(surface, {}))
        missing = {n for n in names if n not in known}
        if surface == "asop":
            missing |= {n for n in names if n not in columns}
        if missing:
            out[surface] = sorted(missing)
    return out


def issue(version: str, missing: Mapping[str, list[str]], locked: Optional[str]) -> tuple[str, str]:
    """The issue's title and body. The title is the dedupe key."""
    flat = ", ".join(f"{s}.{f}" for s, fs in sorted(missing.items()) for f in fs)
    title = f"asop-spec {version} adds fields the hub does not forward: {flat}"
    body = "\n".join([
        f"asop-spec **{version}** is on PyPI; this hub locks **{locked or 'unknown'}**.",
        "",
        "Fields in the new release the hub does not know or store:",
        "",
        *[f"- `{s}`: {', '.join(f'`{f}`' for f in fs)}" for s, fs in sorted(missing.items())],
        "",
        "Proposed update (one PR):",
        "",
        f"- [ ] lock: `uv lock --upgrade-package asop-spec` to {version}; keep the pin `>=0.4.0,<1` "
        "unless the release says otherwise",
        "- [ ] allowlists: the route wire maps (`SOP_BODY_KEYS`, `RUN_BODY_FIELDS`) take the new "
        "record fields; their signature/dataclass pin tests must pass",
        "- [ ] columns: an additive migration and `ASOP_SCHEMA_COLUMNS` for new ASOP record fields "
        "(the import-time guard fails until this is done)",
        f"- [ ] provenance table: `python tools/asop_fields.py regenerate {version}`",
        "- [ ] docs/asop.md: the compatibility matrix gains the release",
        "",
        "Opened by the scheduled `asop-spec watch` job. It opens at most one issue per title.",
    ])
    return title, body


def should_open(title: str, open_titles: Iterable[str]) -> bool:
    return title not in set(open_titles)


def _gh(*args: str) -> str:
    return subprocess.run(["gh", *args], check=True, capture_output=True, text=True).stdout


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    regen = sub.add_parser("regenerate")
    regen.add_argument("versions", nargs="*")
    watch = sub.add_parser("watch")
    watch.add_argument("--github", action="store_true")
    args = parser.parse_args(argv)

    if args.cmd == "regenerate":
        versions = sorted(set(known_releases()) | set(args.versions), key=version_key)
        if not versions:
            parser.error("name at least one version")
        dumps = {v: introspect(v) for v in versions}
        TABLE.write_text(render(provenance(dumps), versions))
        print(f"wrote {TABLE.relative_to(ROOT)} from {', '.join(versions)}")
        return 0

    sys.path.insert(0, str(ROOT))
    from agentco import field_provenance
    from agentco.sqlstore import ASOP_SCHEMA_COLUMNS

    locked = locked_version(LOCK.read_text())
    newest = latest_on_pypi()
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if locked and version_key(newest) <= version_key(locked):
        print(f"asop-spec {newest} on PyPI; the lock has {locked}. Nothing to do.")
        return 0
    missing = new_fields(introspect(newest), field_provenance.FIELDS, ASOP_SCHEMA_COLUMNS)
    if not missing:
        print(f"asop-spec {newest} is newer than the lock ({locked}) but adds no field the hub does not know.")
        return 0
    title, body = issue(newest, missing, locked)
    print(title + "\n\n" + body)
    if summary:
        Path(summary).write_text(f"## {title}\n\n{body}\n")
    if not args.github:
        return 1
    existing = json.loads(_gh("issue", "list", "--state", "open", "--limit", "200", "--json", "title"))
    if should_open(title, (i["title"] for i in existing)):
        _gh("issue", "create", "--title", title, "--body", body)
        print("opened the issue")
    else:
        print("an open issue with this title exists; not opening another")
    return 0


if __name__ == "__main__":
    sys.exit(main())
